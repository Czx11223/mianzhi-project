def resolve_family(job_name: str) -> str:
    """岗位名 → 岗位族；未知岗位走关键词兜底，仍无命中则 general。"""
    name = (job_name or "").strip()
    if name in JOB_FAMILY:
        return JOB_FAMILY[name]
    for keywords, family in KEYWORD_RULES:
        if any(k in name for k in keywords):
            return family
    return "general"


def family_label(family: str) -> str:
    return FAMILY_LABELS.get(family, family or "通用岗位")
